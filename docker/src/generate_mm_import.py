# ============================================================
# チャンネル参加設定
# ============================================================

CATEGORY_TO_CHANNELS = {}

for name, display_name, purpose, header, category in CHANNELS:

    CATEGORY_TO_CHANNELS.setdefault(category, []).append(name)


# 全員参加するチャンネル
ALWAYS_ON = [
    "town-square",
    "break-room",
    "one-liner",
    "announcements",
    "faq",
]


ALL_CHANNEL_NAMES = [
    channel[0]
    for channel in CHANNELS
]


for user in USERS:

    member_channels = set(ALWAYS_ON)

    # ペルソナの興味分野
    for category in user["fav_categories"]:

        for channel_name in CATEGORY_TO_CHANNELS.get(category, []):

            member_channels.add(channel_name)

    # ランダムに追加参加
    extra_count = random.randint(3, 7)

    extra_channels = random.sample(
        ALL_CHANNEL_NAMES,
        k=min(extra_count, len(ALL_CHANNEL_NAMES)),
    )

    member_channels.update(extra_channels)

    user["channels"] = sorted(member_channels)


# ============================================================
# 各チャンネル最低5人を保証
# ============================================================

channel_members = {
    channel[0]: set()
    for channel in CHANNELS
}


for user in USERS:

    for channel_name in user["channels"]:

        channel_members[channel_name].add(
            user["username"]
        )


for channel_name, members in channel_members.items():

    if len(members) >= 5:
        continue

    need = 5 - len(members)

    candidates = [
        user
        for user in USERS
        if channel_name not in user["channels"]
    ]

    random.shuffle(candidates)

    for user in candidates[:need]:

        user["channels"].append(channel_name)

        channel_members[channel_name].add(
            user["username"]
        )


