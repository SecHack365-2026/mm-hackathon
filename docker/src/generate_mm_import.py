def build_post(team, channel_name, category, user_pool):

    bank = BANK[category]

    author = random.choice(user_pool)

    message = random.choice(
        bank["singles"]
    )

    post = {
        "team": team,
        "channel": channel_name,
        "user": author,
        "message": message,
        "create_at": next_ts(),
    }


    # --------------------------------------------------------
    # リアクション
    # --------------------------------------------------------

    if random.random() < 0.55 and len(user_pool) > 1:

        n_react = random.randint(
            1,
            min(4, len(user_pool))
        )

        reactors = random.sample(
            user_pool,
            n_react
        )

        seen = set()

        reactions = []

        for reactor in reactors:

            emoji = random.choice(
                EMOJI_POOL
            )

            key = (
                reactor,
                emoji
            )

            if key in seen:
                continue

            seen.add(key)

            reactions.append(
                {
                    "user": reactor,
                    "emoji_name": emoji,
                    "create_at": next_ts(500, 5000),
                }
            )

        if reactions:
            post["reactions"] = reactions


    # --------------------------------------------------------
    # スレッド返信
    # --------------------------------------------------------

    if random.random() < 0.35 and len(user_pool) > 1:

        n_replies = random.randint(1, 5)

        replies = []

        reply_pool = (
            bank["replies"]
            + GENERIC_FOLLOWUPS
        )

        for _ in range(n_replies):

            replier = random.choice(
                user_pool
            )

            reply_message = random.choice(
                reply_pool
            )

            reply = {
                "user": replier,
                "message": reply_message,
                "create_at": next_ts(
                    2000,
                    600000
                ),
            }


            # 返信にも一部リアクションを付ける
            if random.random() < 0.30:

                n_reply_reactions = random.randint(
                    1,
                    2
                )

                reactors = random.sample(
                    user_pool,
                    min(
                        n_reply_reactions,
                        len(user_pool)
                    )
                )

                reply["reactions"] = [
                    {
                        "user": reactor,
                        "emoji_name": random.choice(
                            EMOJI_POOL
                        ),
                        "create_at": next_ts(
                            500,
                            5000
                        ),
                    }
                    for reactor in reactors
                ]

            replies.append(reply)

        post["replies"] = replies


    return post


