STREAM_JSON_PATH = os.path.join(OUT_DIR, "stream_posts.json")


def main():

    print("=" * 60)
    print("Mattermost ダミーデータ生成 (9割インポート / 1割ストリーミング用)")
    print("=" * 60)

    print()

    print(f"Team     : 1")
    print(f"Channels : {len(CHANNELS)}")
    print(f"Users    : {len(USERS)}")

    print()

    # --------------------------------------------------------
    # データ生成
    # --------------------------------------------------------

    lines = generate_lines()

    # メタ情報（version, team, channel, user）と投稿（post）を分離
    meta_lines = [l for l in lines if l["type"] != "post"]
    post_lines = [l for l in lines if l["type"] == "post"]

    # 9割と1割に分割
    split_idx = int(len(post_lines) * 0.9)
    import_posts = post_lines[:split_idx]
    stream_posts = post_lines[split_idx:]

    # --------------------------------------------------------
    # 1. インポート用 JSONL (9割) を書き出す
    # --------------------------------------------------------

    import_lines = meta_lines + import_posts

    with open(
        JSONL_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        for obj in import_lines:

            file.write(
                json.dumps(
                    obj,
                    ensure_ascii=False,
                    separators=(", ", ": "),
                )
            )

            file.write("\n")

    # --------------------------------------------------------
    # インポート用 ZIP 作成
    # --------------------------------------------------------

    with zipfile.ZipFile(
        ZIP_PATH,
        "w",
        zipfile.ZIP_DEFLATED,
    ) as zip_file:

        zip_file.write(
            JSONL_PATH,
            arcname="import.jsonl",
        )

    # --------------------------------------------------------
    # 2. cron投稿用 JSON (1割) を書き出す
    # --------------------------------------------------------

    stream_data = []
    for p in stream_posts:
        post_info = p["post"]
        stream_data.append(
            {
                "channel_name": post_info["channel"],
                "username": post_info["user"],
                "message": post_info["message"],
                # スレッド返信が存在する場合は保持
                "replies": post_info.get("replies", []),
            }
        )

    with open(
        STREAM_JSON_PATH,
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            stream_data,
            file,
            ensure_ascii=False,
            indent=2,
        )

    # --------------------------------------------------------
    # 件数集計 (全体・インポート用・ストリーム用)
    # --------------------------------------------------------

    n_users = sum(1 for line in lines if line["type"] == "user")

    n_channels = sum(1 for line in lines if line["type"] == "channel")

    n_import_posts = len(import_posts)
    n_stream_posts = len(stream_posts)

    n_replies = sum(
        len(line["post"].get("replies", []))
        for line in lines
        if line["type"] == "post"
    )

    n_reactions = sum(
        len(line["post"].get("reactions", []))
        for line in lines
        if line["type"] == "post"
    )

    n_reply_reactions = sum(
        len(reply.get("reactions", []))
        for line in lines
        if line["type"] == "post"
        for reply in line["post"].get("replies", [])
    )

    n_reactions += n_reply_reactions

    # --------------------------------------------------------
    # 結果表示
    # --------------------------------------------------------

    print("=" * 60)
    print("生成完了")
    print("=" * 60)

    print()

    print(f"lines total   : {len(lines)}")
    print(f"users         : {n_users}")
    print(f"channels      : {n_channels}")
    print(
        f"root posts    : {len(post_lines)} (Import: {n_import_posts} / Stream: {n_stream_posts})"
    )
    print(f"replies       : {n_replies}")
    print(f"reactions     : {n_reactions}")

    print()

    print(f"Import ZIP    : {ZIP_PATH}")
    print(f"Stream JSON   : {STREAM_JSON_PATH}")

    print()

    print("Mattermostへのインポート例:")
    print()
    print(f'mmctl import process "{ZIP_PATH}"')

    print()
    print("=" * 60)

