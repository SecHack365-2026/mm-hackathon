def find_user_by_persona(persona_key, fallback_pool):
    """指定ペルソナのユーザーを優先して選ぶ。見つからなければ通常の参加者から選ぶ。"""
    candidates = [
        user["username"]
        for user in USERS
        if user.get("persona") == persona_key
    ]
    candidates = [u for u in candidates if u in fallback_pool]
    if candidates:
        return random.choice(candidates)
    return random.choice(fallback_pool)


def build_story_posts():
    """複数チャンネルを横断する小さなストーリー群を投稿オブジェクトへ変換する。"""
    posts = []

    for arc in STORY_ARCS:
        for channel_name, category, persona_key, message in arc["steps"]:
            pool = pick_channel_members(channel_name)
            if not pool:
                continue

            author = find_user_by_persona(persona_key, pool)
            post = {
                "team": TEAM_NAME,
                "channel": channel_name,
                "user": author,
                "message": message,
                "create_at": next_ts(15_000, 1_800_000),
            }

            # ストーリー投稿は通常投稿より少し返信されやすくする。
            if random.random() < 0.72 and len(pool) > 1:
                reply_count = random.choices(
                    [1, 2, 3],
                    weights=[5, 4, 1],
                    k=1,
                )[0]
                replies = []
                for _ in range(reply_count):
                    replier = random.choice(pool)
                    reply = {
                        "user": replier,
                        "message": random.choice(STORY_REPLIES),
                        "create_at": next_ts(2_000, 180_000),
                    }
                    if random.random() < 0.25:
                        reply["reactions"] = [{
                            "user": random.choice(pool),
                            "emoji_name": random.choice(EMOJI_POOL),
                            "create_at": next_ts(500, 5_000),
                        }]
                    replies.append(reply)
                post["replies"] = replies

            if random.random() < 0.68 and len(pool) > 1:
                reactors = random.sample(pool, min(random.randint(1, 3), len(pool)))
                post["reactions"] = [
                    {
                        "user": reactor,
                        "emoji_name": random.choice(EMOJI_POOL),
                        "create_at": next_ts(500, 5_000),
                    }
                    for reactor in reactors
                ]

            posts.append(post)

    return posts


def generate_lines():

    lines = []


    # --------------------------------------------------------
    # version
    # --------------------------------------------------------

    lines.append(
        {
            "type": "version",
            "version": 1,
        }
    )


    # --------------------------------------------------------
    # team
    # --------------------------------------------------------

    lines.append(
        {
            "type": "team",
            "team": TEAM,
        }
    )


    # --------------------------------------------------------
    # channel
    # --------------------------------------------------------

    for (
        name,
        display_name,
        purpose,
        header,
        category,
    ) in CHANNELS:

        lines.append(
            {
                "type": "channel",
                "channel": {
                    "team": TEAM_NAME,
                    "name": name,
                    "display_name": display_name,
                    "type": "O",
                    "purpose": purpose,
                    "header": header,
                },
            }
        )


    # --------------------------------------------------------
    # user
    # --------------------------------------------------------

    for user in USERS:

        if user["roles"].startswith(
            "system_admin"
        ):
            team_roles = "team_admin team_user"
        else:
            team_roles = "team_user"


        teams_block = [
            {
                "name": TEAM_NAME,
                "roles": team_roles,
                "channels": [
                    {
                        "name": channel_name,
                        "roles": "channel_user",
                    }
                    for channel_name in user["channels"]
                ],
            }
        ]


        lines.append(
            {
                "type": "user",
                "user": {
                    "username": user["username"],
                    "email": user["email"],
                    "nickname": user["nickname"],
                    "first_name": user["first_name"],
                    "last_name": user["last_name"],
                    "roles": user["roles"],
                    "teams": teams_block,
                },
            }
        )


    # --------------------------------------------------------
    # post
    # --------------------------------------------------------

    post_objects = []

    # --------------------------------------------------------
    # ストーリー投稿（複数チャンネルをまたぐ連続イベント）
    # --------------------------------------------------------
    post_objects.extend(build_story_posts())


    for (
        name,
        display_name,
        purpose,
        header,
        category,
    ) in CHANNELS:

        post_count = (
            POST_COUNT_BY_CATEGORY_WEIGHT.get(
                category,
                60
            )
        )

        user_pool = pick_channel_members(
            name
        )

        if not user_pool:
            continue


        for _ in range(post_count):

            post_objects.append(
                build_post(
                    TEAM_NAME,
                    name,
                    category,
                    user_pool,
                )
            )


    # --------------------------------------------------------
    # 時系列順にソート
    # --------------------------------------------------------

    post_objects.sort(
        key=lambda post: post["create_at"]
    )


    for post in post_objects:

        lines.append(
            {
                "type": "post",
                "post": post,
            }
        )


    return lines


